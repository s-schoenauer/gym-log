"""Merge the literature-review JSON files into src/evidence.ts.

Usage: python3 scripts/build-evidence.py <review.json> [...]
Each file: {"exercises": [{nameEn, variants: [{key, labelDe, labelEn, targets, basis, summaryDe, sourceIds}], myths}], "sources": [{id, cite, url, type, finding}]}
Source ids are prefixed per file so they stay unique. Exercises are keyed by slug(nameEn), matching src/db.ts.
"""
import json, re, sys, unicodedata, pathlib

KEYS = {'pec_clav', 'pec_sternal', 'delt_ant', 'delt_lat', 'delt_post', 'lats', 'traps_upper', 'upper_back', 'erectors',
        'biceps', 'brachialis', 'brachioradialis', 'tri_long', 'tri_lat_med', 'forearm_flex', 'quads', 'rectus_femoris',
        'hamstrings', 'glutes', 'adductors', 'calves', 'abs', 'obliques'}
BASIS = {'hypertrophy', 'emg', 'biomech', 'mixed'}

def slug(s):
    s = unicodedata.normalize('NFKD', s.lower())
    return re.sub(r'^_|_$', '', re.sub(r'[^\w]+', '_', s))

# USER_VARIANTS lives in its own small file so it survives regeneration
user_variants = json.loads(pathlib.Path(__file__).with_name('user-variants.json').read_text())

evidence, sources, problems = {}, {}, []
for path in sys.argv[1:]:
    data = json.loads(pathlib.Path(path).read_text())
    prefix = pathlib.Path(path).stem.split('_')[0]
    for s in data['sources']:
        sources[f"{prefix}_{s['id']}"] = {k: s.get(k, '') for k in ('cite', 'url', 'type', 'finding')}
    for ex in data['exercises']:
        key = slug(ex['nameEn'])
        variants = []
        for v in ex['variants']:
            t = {}
            for m, w in v['targets'].items():
                if m not in KEYS: problems.append(f'{key}/{v["key"]}: unknown muscle {m}'); continue
                if w not in (1, 0.5): problems.append(f'{key}/{v["key"]}: weight {w} for {m} rounded'); w = 1 if w >= 0.75 else 0.5
                t[m] = w
            basis = v.get('basis', 'mixed')
            if basis not in BASIS: problems.append(f'{key}: basis {basis}'); basis = 'mixed'
            ids = [f'{prefix}_{i}' for i in v.get('sourceIds', [])]
            for i in ids:
                if i not in sources: problems.append(f'{key}: missing source {i}')
            variants.append({'key': v['key'], 'labelDe': v.get('labelDe', ''), 'labelEn': v.get('labelEn', ''), 'targets': t,
                             'basis': basis, 'summaryDe': v.get('summaryDe', ''), 'sourceIds': [i for i in ids if i in sources]})
        evidence[key] = {'variants': variants, 'myths': ex.get('myths', [])}

for k, v in user_variants.items():
    if k not in evidence: problems.append(f'user variant for unknown exercise {k}')
    elif v not in [x['key'] for x in evidence[k]['variants']]: problems.append(f'user variant {k}={v} not in {[x["key"] for x in evidence[k]["variants"]]}')

head = pathlib.Path('src/evidence.ts').read_text().split('export const EVIDENCE')[0]
head = head.replace('// Placeholder – generated', '// GENERATED by scripts/build-evidence.py – do not edit by hand. Generated')
out = head + 'export const EVIDENCE: Record<string, Evidence> = ' + json.dumps(evidence, ensure_ascii=False, indent=1) + ';\n\n'
out += 'export const SOURCES: Record<string, Source> = ' + json.dumps(sources, ensure_ascii=False, indent=1) + ';\n\n'
out += '/** Execution the user described, per exercise key. */\nexport const USER_VARIANTS: Record<string, string> = ' + json.dumps(user_variants, ensure_ascii=False) + ';\n'
pathlib.Path('src/evidence.ts').write_text(out)
print(f'{len(evidence)} exercises, {len(sources)} sources')
for p in problems: print('WARN', p)
